function Show-Clock {
    while ($true) {
        Clear-Host

        $t = (Get-Date).ToString("HH:mm:ss")

        $lines = @("","","","","","","")

        foreach ($c in $t.ToCharArray()) {

        
            if (-not $NUM.ContainsKey($c)) {
                $glyph = @("      ","      ","      ","      ","      ","      ","      ")
            } else {
                $glyph = $NUM[$c]
            }

            for ($i = 0; $i -lt 7; $i++) {
                $lines[$i] += $glyph[$i] + "  "
            }
        }

        $lines | ForEach-Object { Write-Host $_ }
        Start-Sleep -Milliseconds 500
    }
}

Show-Clock
